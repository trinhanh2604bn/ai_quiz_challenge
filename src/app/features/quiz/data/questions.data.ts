function assertQuestionBank(questions: readonly Question[]): void {
  const ids = new Set<string>();
  const counts = new Map<string, number>();

  for (const question of questions) {
    if (ids.has(question.id)) {
      throw new Error(`Duplicate question id: ${question.id}`);
    }
    ids.add(question.id);

    if (question.options.length !== 4) {
      throw new Error(`Question ${question.id} must have four options`);
    }

    if (
      question.correctIndex !== 0 &&
      question.correctIndex !== 1 &&
      question.correctIndex !== 2 &&
      question.correctIndex !== 3
    ) {
      throw new Error(`Invalid correctIndex for ${question.id}`);
    }

    const key = `${question.category}\0${question.difficulty}`;
    counts.set(key, (counts.get(key) ?? 0) + 1);
  }

  for (const category of QUESTION_CATEGORIES) {
    for (const difficulty of DIFFICULTY_LEVELS) {
      const count = counts.get(`${category}\0${difficulty}`) ?? 0;
      if (count < 10) {
        throw new Error(
          `Expected at least 10 questions for ${category} (${difficulty}), found ${count}`,
        );
      }
    }
  }
}

assertQuestionBank(QUESTIONS);
